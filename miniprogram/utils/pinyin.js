function isChineseChar(ch) {
  const cp = ch.codePointAt(0)
  return cp >= 0x3400 && cp <= 0x9FFF
}

/**
 * 返回字符串首字的拼音首字母大写
 * @param {string} value 任意字符串
 * @returns {string} A-Z 或 '#'（英文字母/非汉字/罕见字兜底）
 */
function getPinyinInitial(value) {
  const text = String(value || '').trim()
  if (!text) return '#'
  const ch = text[0]

  // 英文字母直接返回大写
  if (/^[A-Za-z]$/.test(ch)) return ch.toUpperCase()

  // 非汉字直接返回 #
  if (!isChineseChar(ch)) return '#'

  // 常见字命中直接返回，保证真模一致
  const hit = COMMON_CHAR_MAP[ch]
  if (hit) return hit

  // 罕见字兜底：统一返回 '#'，避免不同环境 localeCompare 结果不一致。
  // 遇到了直接在上面 COMMON_CHAR_MAP 里加一行即可。
  return '#'
}

